# FOOTNOTE: 26年度だけ前年度、3年度前などと表記が変わっている。元号も扱いにくいので、全てnXXXX_という名前に変えておく
rename_helper_23to25 <- function(cnn,current="n2022_"){
  cnn |> 
    rename_with(~{str_replace(.x,"平成30年度","n2018_")}) |> 
    rename_with(~{str_replace(.x,"令和1年度" ,"n2019_")}) |> 
    rename_with(~{str_replace(.x,"令和2年度" ,"n2020_")}) |> 
    rename_with(~{str_replace(.x,"令和3年度" ,"n2021_")}) |>
    rename_with(~{str_replace(.x,"令和4年度" ,"n2022_")}) |> 
    rename_with(~{str_replace(.x,"令和5年度" ,"n2023_")}) |>
    rename_with(~{str_replace(.x,"^(?=総合偏差値)",current)}) |>  
    rename_with(~{str_replace(.x,"^(?=側面)",current)}) 
}

rename_helper_26on <- function(cnn,currentnum){
  cnn |> 
    rename_with(~{str_replace(.x,"^(?=総合偏差値)",str_c("n",currentnum,"_"))}) |>  
    rename_with(~{str_replace(.x,"^(?=側面)"      ,str_c("n",currentnum,"_"))}) |>  
    rename_with(~{str_replace(.x,"前年度"         ,str_c("n",currentnum-1,"_"))}) |> 
    rename_with(~{str_replace(.x,"前々年度"       ,str_c("n",currentnum-2,"_"))}) |> 
    rename_with(~{str_replace(.x,"3年度前"        ,str_c("n",currentnum-3,"_"))}) |> 
    rename_with(~{str_replace(.x,"4年度前"        ,str_c("n",currentnum-4,"_"))})  
}

normalize_name <- function(x) {
  x |>
    # NA -> ""
    coalesce("") |>
    # 全角英数 → 半角
    str_replace_all("[Ａ-Ｚａ-ｚ０-９]", \(s) {
      chartr("ＡＢＣＤＥＦＧＨＩＪＫＬＭＮＯＰＱＲＳＴＵＶＷＸＹＺａｂｃｄｅｆｇｈｉｊｋｌｍｎｏｐｑｒｓｔｕｖｗｘｙｚ０１２３４５６７８９",
             "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789", s)
    }) |>
    # 全角スペース・記号
    str_replace_all("　", "") |>
    # 連続スペース・前後スペース・全空白除去
    str_replace_all("\\s+", "") |>
    # 大文字化(英字)
    str_to_upper() |>
    # 句読点・記号
    str_replace_all("[・･,，.\\.\\-‐－—–=＝/／&＆\\(\\)（）「」『』\\[\\]【】<>＜＞]", "")
}

