make_panel_siden <- function(combined, sidenum){
  combined |> 
    select(nendo, fixedcode, matches(str_c("側面",sidenum,".+偏差値"))) |> 
    pivot_longer(cols = !c(nendo,fixedcode)) |>
    mutate(name = str_replace(name,str_c("側面",sidenum,".+"),str_c("side",sidenum)))|> 
    filter(!is.na(value)) |> 
    select(fixedcode, name, value) |> 
    distinct() |> 
    pivot_wider(id_cols = fixedcode, names_from = name, values_from = value)
}

